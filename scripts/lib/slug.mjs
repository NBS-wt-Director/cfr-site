/**
 * scripts/lib/slug.mjs — имя сущности в URL-якорь (S18).
 *
 * Slug = имя «КАК ЗАПИСАНО» в базе, кириллицей, БЕЗ транслитерации:
 *   «Глазырин Михаил» → «Глазырин-Михаил»
 *   «Таицзи-Цюань»    → «Таицзи-Цюань»
 *   «Крепыши (2-4 года)» → «Крепыши-2-4-года»
 *
 * Правила:
 *   - пробелы, подчёркивания и слэши → «-»;
 *   - всё, кроме букв (кириллица/латиница), цифр и «-», вырезается
 *     (скобки, точки, запятые, кавычки);
 *   - подряд идущие «-» сворачиваются, ведущие/замыкающие срезаются;
 *   - РЕГИСТР и Ё сохраняются — slug пишется как имя в базе.
 *
 * В URL кириллица уходит через encodeURIComponent (браузер показывает её же).
 * entity.js резолвит slug точно (как записано), а при промахе — нестрого
 * (регистр + ё/е, для ссылок набранных вручную). Всё остальное — 404.
 * Совпадение с browser-версией static/js/slug.js проверяет тест S18.
 */

export function slugify(str) {
  return String(str == null ? '' : str)
    .trim()
    .replace(/[\s_/]+/g, '-')
    .replace(/[^а-яёА-ЯЁa-zA-Z0-9-]/g, '')
    .replace(/-{2,}/g, '-')
    .replace(/^-+|-+$/g, '');
}
