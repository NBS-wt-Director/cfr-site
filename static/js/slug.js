/**
 * slug.js — транслитерация ФИО/названий в URL-якорь (S18).
 *
 * Единый алгоритм с scripts/lib/slug.mjs (node-сторона: sitemap, экспорт).
 * Совпадение двух реализаций проверяет регресс-тест S18 в test-static.mjs.
 *
 * Правила:
 *   - кириллица → латиница (таблица ниже), ё→e, й→i, ы→y, щ→sch;
 *   - всё, что не [a-z0-9], становится «-»; подряд идущие «-» сворачиваются;
 *   - ведущие/замыкающие «-» срезаются.
 *
 * Ссылки вида program.html?id=<slug> резолвятся entity.js; числовой ?id=<id>
 * остаётся рабочим (обратная совместимость внешних ссылок и sitemap прошлых лет).
 */
(function () {
  var MAP = {
    'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'ё': 'e',
    'ж': 'zh', 'з': 'z', 'и': 'i', 'й': 'i', 'к': 'k', 'л': 'l', 'м': 'm',
    'н': 'n', 'о': 'o', 'п': 'p', 'р': 'r', 'с': 's', 'т': 't', 'у': 'u',
    'ф': 'f', 'х': 'kh', 'ц': 'ts', 'ч': 'ch', 'ш': 'sh', 'щ': 'sch',
    'ъ': '', 'ы': 'y', 'ь': '', 'э': 'e', 'ю': 'yu', 'я': 'ya'
  };

  window.slugify = function (str) {
    var s = String(str == null ? '' : str).toLowerCase();
    var out = '';
    for (var i = 0; i < s.length; i++) {
      var ch = s[i];
      if (MAP[ch] !== undefined) out += MAP[ch];
      else out += ch;
    }
    return out
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '');
  };
})();
