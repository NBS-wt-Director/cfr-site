/**
 * slug.js — имя сущности в URL-якорь (S18), браузерная версия.
 *
 * Slug = имя «КАК ЗАПИСАНО» в базе, кириллицей, БЕЗ транслитерации:
 *   «Глазырин Михаил» → «Глазырин-Михаил»
 *   «Таицзи-Цюань»    → «Таицзи-Цюань»
 *
 * Единый алгоритм с scripts/lib/slug.mjs (node-сторона: sitemap, экспорт).
 * Совпадение двух реализаций проверяет регресс-тест S18 в test-static.mjs.
 *
 * Ссылки вида program.html?id=<кириллический-slug> резолвятся entity.js;
 * числовой ?id=<id> остаётся рабочим (обратная совместимость внешних ссылок).
 * Всё, что не совпало ни с одним slug/id, — 404.
 */
(function () {
  window.slugify = function (str) {
    return String(str == null ? '' : str)
      .trim()
      .replace(/[\s_/]+/g, '-')
      .replace(/[^а-яёА-ЯЁa-zA-Z0-9-]/g, '')
      .replace(/-{2,}/g, '-')
      .replace(/^-+|-+$/g, '');
  };
})();
